#!/usr/bin/env python
"""Create (or redeploy) the graphwright web service on Render's free plan.

Auth: reads RENDER_API_KEY from the environment, else from ~/.render-api-key.
Values for NEO4J_* come from .env; MCP_AUTH_TOKEN is generated by Render.

    uv run python scripts/render_deploy.py            # create if missing, then deploy
    uv run python scripts/render_deploy.py --status   # print service + deploy state
"""

from __future__ import annotations

import argparse
import json
import os
import pathlib
import sys
import time
import urllib.error
import urllib.request

API = 'https://api.render.com/v1'
SERVICE_NAME = os.getenv('RENDER_SERVICE_NAME', 'graphwright')
REPO = os.getenv('RENDER_REPO', 'https://github.com/programisfun/graphwright')
BRANCH = os.getenv('RENDER_BRANCH', 'main')
REGION = os.getenv('RENDER_REGION', 'oregon')


def api_key() -> str:
    """RENDER_API_KEY from env, scripts/.env.deploy, or ~/.render-api-key."""
    key = os.getenv('RENDER_API_KEY')
    if key:
        return key.strip()

    candidates = [
        pathlib.Path(__file__).parent / '.env',           # scripts/.env
        pathlib.Path(__file__).parent / '.env.deploy',    # scripts/.env.deploy
        pathlib.Path.home() / '.render-api-key',          # outside the repo
    ]
    for path in candidates:
        if not path.exists():
            continue
        text = path.read_text(encoding='utf-8')
        for line in text.splitlines():
            line = line.strip()
            if line.startswith('RENDER_API_KEY='):
                value = line.split('=', 1)[1].strip().strip('"').strip("'")
                if value:
                    return value
        if path.name == '.render-api-key' and text.strip():
            return text.strip()

    sys.exit(
        'No API key. Create one at https://dashboard.render.com/u/settings#api-keys '
        'then either:\n'
        '  echo "RENDER_API_KEY=rnd_..." > scripts/.env.deploy\n'
        '  or set RENDER_API_KEY'
    )


def call(method: str, path: str, body: dict | None = None) -> object:
    data = json.dumps(body).encode() if body is not None else None
    request = urllib.request.Request(
        f'{API}{path}',
        data=data,
        method=method,
        headers={
            'Authorization': f'Bearer {api_key()}',
            'Content-Type': 'application/json',
            'Accept': 'application/json',
        },
    )
    try:
        with urllib.request.urlopen(request, timeout=60) as response:
            raw = response.read()
            return json.loads(raw) if raw else None
    except urllib.error.HTTPError as error:
        detail = error.read().decode(errors='replace')
        sys.exit(f'{method} {path} -> HTTP {error.code}: {detail[:600]}')


def env_file_values() -> dict[str, str]:
    """Read NEO4J_* from .env (via python-dotenv) without printing secrets."""
    from dotenv import dotenv_values

    values = dotenv_values('.env')
    required = ('NEO4J_URI', 'NEO4J_USER', 'NEO4J_PASSWORD', 'NEO4J_DATABASE')
    missing = [name for name in required if not values.get(name)]
    if missing:
        sys.exit(f'.env is missing: {", ".join(missing)}')
    return {name: values[name] for name in required}


def owner_id() -> str:
    owners = call('GET', '/owners?limit=1')
    if not owners:
        sys.exit('No Render workspace found for this API key.')
    return owners[0]['owner']['id']


def find_service() -> dict | None:
    services = call('GET', '/services?limit=100') or []
    for item in services:
        service = item['service']
        if service['name'] == SERVICE_NAME:
            return service
    return None


def create_service(owner: str) -> dict:
    payload = {
        'type': 'web_service',
        'name': SERVICE_NAME,
        'ownerId': owner,
        'repo': REPO,
        'branch': BRANCH,
        'autoDeployTrigger': 'commit',
        'envVars': [
            *[{'key': k, 'value': v} for k, v in env_file_values().items()],
            {'key': 'MCP_STATELESS', 'value': '1'},
            {'key': 'MCP_AUTH_TOKEN', 'generateValue': True},
        ],
        'serviceDetails': {
            'runtime': 'docker',
            'plan': 'free',
            'region': REGION,
            'healthCheckPath': '/health',
            'envSpecificDetails': {'dockerfilePath': './Dockerfile'},
        },
    }
    created = call('POST', '/services', payload)
    return created['service']


def deploy(service_id: str) -> str:
    result = call('POST', f'/services/{service_id}/deploys', {'clearCache': 'do_not_clear'})
    return result['id'] if isinstance(result, dict) else result[0].get('deploy', {}).get('id')


def wait_for_deploy(service_id: str, deploy_id: str, timeout_s: int = 900) -> str:
    deadline = time.time() + timeout_s
    last = None
    while time.time() < deadline:
        deploy = call('GET', f'/services/{service_id}/deploys/{deploy_id}')
        status = deploy['status']
        if status != last:
            print(f'  deploy status: {status}', flush=True)
            last = status
        if status in ('live', 'build_failed', 'update_failed', 'canceled', 'deactivated'):
            return status
        time.sleep(10)
    return 'timeout'


def show(service: dict) -> None:
    details = service.get('serviceDetails') or {}
    print(f"service : {service['name']} ({service['id']})")
    print(f"plan    : {details.get('plan')}   region: {details.get('region')}")
    print(f"url     : {details.get('url')}")
    print(f"health  : {service.get('healthCheckPath') or details.get('healthCheckPath')}")
    print(f"mcp     : {(details.get('url') or '')}/mcp")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument('--status', action='store_true', help='only print current state')
    args = parser.parse_args()

    service = find_service()
    if service is None:
        if args.status:
            sys.exit(f'No service named {SERVICE_NAME!r} in this workspace.')
        print(f'Creating {SERVICE_NAME!r} from {REPO} ({BRANCH}, {REGION}, free)')
        service = create_service(owner_id())
    else:
        print(f'Found existing service {service["id"]}')

    show(service)
    if args.status:
        return

    deploy_id = deploy(service['id'])
    print(f'\nDeploy started: {deploy_id}')
    status = wait_for_deploy(service['id'], deploy_id)
    print(f'\nDeploy finished: {status}')
    if status == 'live':
        print(f'MCP endpoint: {(service["serviceDetails"].get("url") or "")}/mcp')
        print('Token: read it in the Render dashboard (Environment) — it was generated by Render.')
        sys.exit(0)
    sys.exit(f'Deploy did not go live ({status}). Check the Render logs.')


if __name__ == '__main__':
    main()
